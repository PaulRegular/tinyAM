  out$is_current <- if (current) "TRUE" else "FALSE"; out$is_applied <- "TRUE"
  out$framework_year <- 2025; out$assessment_url <- reference
  out$framework_url <- urls[["model"]]
  out$data_url <- if (current) urls[["data"]] else ""
  out$assumptions_status <- out$inputs_status <- out$outputs_status <- "partial"
  out$notes <- notes
  out
}
