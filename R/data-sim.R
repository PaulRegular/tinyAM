#' Simulated cod fisheries and surveys
#'
#' @description
#' A teaching dataset loosely based on 3Ps cod, with three active fisheries and
#' two surveys of a shared population. The fishing grounds and survey programs
#' illustrate inshore and offshore fishing and monitoring practices. The trawl
#' fleet continues at a bycatch level after directed fishing ends in year 10.
#'
#' @format
#' `sim_cod_obs` is a `tam_data` list (see [as_tam_data()]) with four tables
#' covering ages 1 through 20.
#' - `catch` gives estimated catch numbers by year, age and fleet. The fleets
#'   are Gillnet, Longline and Trawl.
#' - `index` gives abundance indices by year, age and survey. The RV and Sentinel
#'   programs observe the same annual population snapshot (`samp_time = 0`).
#' - `weight` gives stock and fleet-specific catch weights at age, distinguished
#'   by `type` and `fleet`. Individual weights are in kg.
#' - `maturity` gives the proportion mature at age.
#'
#' Catch and index values are in thousand fish. Multiplying thousands of fish
#' by weight in kg gives biomass or yield in tonnes. Each index estimates
#' abundance within its survey footprint.
#'
#' `sim_cod_truth` keeps generating quantities separate from the fitting data.
#' - `population` gives abundance `N` (thousand fish), biomass `B` and `SSB`
#'   (tonnes), individual weight (kg), maturity, total mortality `Z`, total
#'   fishing mortality `F`, and realized and reference natural mortality
#'   (`M` and `M_reference`, per year), by year and age.
#' - `annual` gives total abundance, recruitment, biomass, SSB and yield in
#'   the same units.
#' - `fleet` gives reference and realized catches (thousand fish) and F (per
#'   year), realized catch weights (kg) and yield (tonnes) by fleet, year and age.
#'   Empty catch cells use stock weight.
#'   `catch_biology` gives monitored catch weights and their support status.
#' - `surveys` gives selectivity, the regional availability fraction, and
#'   regional abundance, total abundance and expected index in thousand fish.
#' - `footprint` gives cell coordinates (km), depth (m), area (square km),
#'   strata and access for each fishery and survey. `selectivity` gives the
#'   generating curves by component and age.
#' - `fishery_annual` and `monitoring` summarize targets, catches and sampling.
#'   `F_full_reference` is the annual target at full selectivity and
#'   `F_full_unreduced` is the target trajectory without the trawl reduction.
#'   `monitoring$status` records whether catch-at-age estimates were supported.
#'   `survey_precision` gives estimated index SEs in thousand fish and the
#'   support status for each survey estimate.
#'   `survey_monitoring` summarizes survey sampling.
#' - `checks` summarizes realized M, including before and after the trawl
#'   reduction, target shortfalls, unsupported observations and survivors
#'   omitted at the terminal simulated age.
#'   `provenance` records the source revision, seeds and runtime.
#'
#' @details
#' The population uses seed 17 and a shared spatial field on a 20-by-20 grid.
#' Each fleet and survey has a stable footprint.
#' Gillnet and longline fleets fish inshore, while trawlers fish offshore. The denser,
#' inshore Sentinel survey has dome-shaped selectivity and uses the same
#' swept-area sampling model as the offshore RV survey, omitting fixed-gear
#' saturation.
#'
#' Each fleet's target fishing mortality at full selectivity (`F_full`)
#' follows an independent random walk on the log scale, generated with seed
#' 1701. The trawl target is multiplied by 0.2 from year 11 onward to represent
#' bycatch. Total mortality combines the age-specific reference fleet rates
#' with an independently generated reference M centred on 0.28 per year
#' to keep realized M near 0.3.
#' SimSurvey allocates fishing removals from those deaths. Realized F depends on
#' which ages are caught and whether fleets meet their targets. Realized M
#' is the remainder of total mortality after subtracting realized fleet F.
#'
#' SimSurvey's `run_catch()` uses randomly sampled ages to estimate catch at
#' age and calibrates the estimates to reported fleet totals. `run_strat()`
#' estimates abundance indices for both survey programs. The data retain
#' supported zero estimates and record unavailable estimates as missing.
#' tinyAM excludes zeros and missing values from its lognormal likelihood.
#' The fit uses expected stock weights and maturity from SimSurvey's
#' `stock_biology()`. Fleet catch weights come from `run_catch()`, with
#' stock weight used for ages lacking a monitored estimate.
#'
#' The guide compares fleet-specific and aggregate fits over ages 1 through 14.
#' tinyAM pools catches and indices for
#' ages 14 and older while retaining weight and maturity through age 20.
#' The simulator ends at age 20 and drops survivors that would reach age 21.
#' This difference matters when comparing the fitted plus group with truth.
#'
#' @source
#' Generated by `data-raw/sim_cod_obs.R` with a recorded development revision
#' of [SimSurvey](https://paulregular.github.io/SimSurvey/).
#'
#' @references
#' Regular, P.M. et al. (2020). SimSurvey: An R package for comparing the design
#' and analysis of surveys by simulating spatially-correlated populations.
#' PLOS ONE 15(5): e0232822. \doi{10.1371/journal.pone.0232822}
#'
#' Varkey, D.A. et al. (2024). Report of the data-review meeting in preparation
#' for the assessment framework of 3Ps Cod stock in southern Newfoundland.
#' Canadian Data Report of Fisheries and Aquatic Sciences 1381.
#' \url{https://publications.gc.ca/collections/collection_2024/mpo-dfo/Fs97-13-1381-eng.pdf}
#'
#' Kumar, R. et al. (2026). Standardized Indices and Biological Information for
#' 3Ps Cod from the Sentinel Gillnet and Linetrawl Surveys using the
#' 'Rsentinel' R-Package. DFO Research Document 2026/056.
#' \url{https://publications.gc.ca/collections/collection_2026/mpo-dfo/fs70-5/Fs70-5-2026-056-eng.pdf}
#'
