test_that('deterministic F uses its mean without unused process parameters', {
 for (formula in list(~1,~factor(age),~mono(age),~logistic(age))) {
  d<-prepare_tam(cod_obs,years=1983:1990,ages=2:6,F_settings=list(process='off',mu_form=formula),proj_settings=list(n_proj=2,F_mult=c(.5,1.5)))
  p<-make_par(d)
  expect_false(any(c('log_f','log_sd_f','logit_phi_f','atanh_rho_f') %in% names(p)))
  p$log_mu_f[1]<-log(.3)
  obj<-RTMB::MakeADFun(function(p)nll_fun(p,d),p,silent=TRUE)
  r<-obj$report(obj$par)
  expect_equal(r$F[!d$is_proj,],r$mu_F[!d$is_proj,],ignore_attr=TRUE)
  expect_equal(r$F[9,],.5*r$F[8,],ignore_attr=TRUE)
  expect_equal(r$F[10,],1.5*r$F[8,],ignore_attr=TRUE)
  expect_true(all(is.finite(obj$gr(obj$par))))
  sim<-nll_fun(p,d,simulate=TRUE)
  expect_false('log_f' %in% names(sim))
  expect_true(all(is.finite(sim$log_obs[d$is_observed])))
 }
 expect_error(prepare_tam(cod_obs,F_settings=list(process='off')), 'mu_form is required')
 expect_error(prepare_tam(cod_obs,F_settings=list(process='off',mu_form=~age+I(2*age))), 'rank-deficient')
 expect_error(prepare_tam(cod_obs,F_settings=list(process='off',mu_form=~1,sd_form=~age)), 'no process')
})

test_that('deterministic F catch targets and recruitment initialization use the same surface', {
 d<-prepare_tam(cod_obs,years=1983:1990,ages=2:6,
  F_settings=list(process='off',mu_form=~factor(age)),
  rec_settings=list(process='iid',mu_form=~bh(ssb)),
  proj_settings=list(n_proj=2,catch=c(0,100)))
 p<-make_par(d);p$log_r0<-log(1e5);p$log_r[]<-log(1e5)
 p<-.initialize_rec_curve(p,d)
 o<-RTMB::MakeADFun(function(p)nll_fun(p,d),p,silent=TRUE)
 r<-o$report(o$par)
 expect_equal(r$total_yield_pred[9:10],c(0,100),tolerance=1e-8,ignore_attr=TRUE)
 expect_equal(r$F[9,],rep(0,5),ignore_attr=TRUE)
 expect_true(all(is.finite(o$gr(o$par))))
 expect_true(all(is.finite(p$log_sr_alpha)))
 expect_equal(r$rec_log_mean[1],p$log_r0,tolerance=1e-8,ignore_attr=TRUE)
})

test_that('formula-driven F supports uncertainty, information criteria and evaluation', {
 g<-expand.grid(year=2000:2039,age=1:7)
 obs<-list(catch=transform(g,obs=100),index=transform(g,obs=100,survey='A',samp_time=.5),
  weight=transform(g,obs=age^2/10),maturity=transform(g,obs=.5*plogis(age-3)))
 args<-list(N_settings=list(process='off'),F_settings=list(process='off',mu_form=~logistic(age)),index_settings=list(q_form=~1))
 d<-do.call(prepare_tam,c(list(data=obs),args));p<-make_par(d)
 p$log_r0<-log(1000);p$log_r[]<-log(1000);p$log_sd_r<-log(.2)
 p$log_mu_f[]<-log(.4);p$log_sd_catch[]<-p$log_sd_index[]<-log(.15)
 p[grep('^F_a50_',names(p))]<-list(3);p[grep('^log_F_slope_',names(p))]<-list(log(.8))
 set.seed(1129);s<-nll_fun(p,d,simulate=TRUE)
 for(type in c('catch','index'))obs[[type]]$obs<-exp(s$log_obs[d$obs_map$type==type])
 f<-do.call(fit_tam,c(list(data=obs,silent=TRUE),args))
 expect_true(f$is_converged)
 expect_false('log_f' %in% f$obj$env$.random)
 expect_equal(attr(logLik(f),'df'),length(f$opt$par))
 ca<-cAIC(f,details=TRUE)
 expect_equal(ca$edf_F,0)
 expect_equal(ca$n_random,39)
 expect_true(all(is.finite(f$pop$F$se)))
 expect_true(all(is.finite(f$pop$mu_F$se)))
 u<-update(f,proj_settings=list(n_proj=2,catch=c(0,100)),start_par=f,silent=TRUE)
 expect_true(u$is_converged)
 bad<-u;bad$rep$log_pred[1]<- -Inf
 expect_equal(subset(check_tam(bad)$numerical,check=='predictions')$status,'fail')
 expect_true(all(u$pop$F$est[u$pop$F$year==2040]==0))
 expect_true(all(u$pop$F$upr[u$pop$F$year==2040]==0))
 h<-fit_hindcast(f,folds=1,start_from_fit=TRUE,proj_settings=list(F_mult=1),progress=FALSE)
 expect_equal(sum(h$fold_diagnostics$is_converged),2)
 expect_true(nrow(h$scores)>0)
 sim<-sim_tam(f,n=1,par_uncertainty='none',redraw_random=TRUE,progress=FALSE,seed=2)
 expect_true(nrow(sim$F)>0)
})
